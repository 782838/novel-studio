// 章节挂到「幕」下，演示按卷分组
let order = 0;
let i = 0;
for (const a of acts) {
  const perAct = Math.ceil(TEXTS.length / acts.length);
  for (let k = 0; k < perAct && i < TEXTS.length; k++, i++) {
    const t = TEXTS[i];
    order++;
    db.chapters.push({
      id: `chap_shot${String(order).padStart(2, '0')}aaa`,
      createdAt: Date.now() + order,
      projectId: pid,
      nodeId: a.id,
      title: t.title,
      summary: t.summary,
      content: t.content,
      status: order <= 4 ? 'done' : order === 5 ? 'draft' : 'todo',
      order
    });
  }
}

fs.writeFileSync(FILE, JSON.stringify(db, null, 2));
